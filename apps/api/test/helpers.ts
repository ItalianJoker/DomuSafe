import { createHmac, randomBytes, randomUUID } from 'node:crypto';
import { createTestDatabase, requireAdminUrl, type TestDatabase } from '@domusafe/db/testing';
import type { FastifyInstance, LightMyRequestResponse } from 'fastify';
import { inject } from 'vitest';
import { buildApp } from '../src/app.js';
import { loadConfig } from '../src/config.js';
import { MemoryStore } from '../src/infra/kv.js';

export const ORIGIN = 'http://localhost:3000';

export interface TestApp {
  readonly app: FastifyInstance;
  readonly database: TestDatabase;
  readonly close: () => Promise<void>;
}

export async function createTestApp(options: { rateLimitPerMinute?: number } = {}): Promise<TestApp> {
  const database = await createTestDatabase(requireAdminUrl(), inject('templateDatabase'));
  const config = loadConfig({
    NODE_ENV: 'test',
    LOG_LEVEL: 'silent',
    PUBLIC_ORIGIN: ORIGIN,
    DATABASE_URL: database.appUrl,
    DATABASE_POOL_SIZE: '4',
    DOMUSAFE_MASTER_KEYS: `1:${randomBytes(32).toString('base64url')}`,
    DOMUSAFE_MASTER_KEY_ACTIVE: '1',
  });
  const app = await buildApp({
    config,
    store: new MemoryStore(),
    globalRateLimitPerMinute: options.rateLimitPerMinute ?? 100_000,
  });
  await app.ready();
  return {
    app,
    database,
    close: async () => {
      await app.close();
      await database.drop();
    },
  };
}

type Method = 'GET' | 'POST' | 'PATCH' | 'DELETE' | 'PUT';

/** Browser-like client: keeps cookies, sends Origin and the anti-CSRF header. */
export class Client {
  readonly #app: FastifyInstance;
  readonly #cookies = new Map<string, string>();

  constructor(app: FastifyInstance) {
    this.#app = app;
  }

  async request(
    method: Method,
    url: string,
    options: { body?: unknown; headers?: Record<string, string>; csrf?: boolean } = {},
  ): Promise<LightMyRequestResponse> {
    const headers: Record<string, string> = { origin: ORIGIN, ...options.headers };
    if (options.csrf !== false) {
      headers['x-domusafe-request'] = '1';
    }
    if (this.#cookies.size > 0) {
      headers.cookie = [...this.#cookies].map(([name, value]) => `${name}=${value}`).join('; ');
    }
    const response = await this.#app.inject({
      method,
      url,
      headers,
      ...(options.body === undefined ? {} : { payload: options.body as Record<string, unknown> }),
    });
    for (const cookie of response.cookies) {
      if (cookie.value === '' || (cookie.maxAge !== undefined && cookie.maxAge <= 0)) {
        this.#cookies.delete(cookie.name);
      } else {
        this.#cookies.set(cookie.name, cookie.value);
      }
    }
    return response;
  }

  create(url: string, body: unknown, key: string = randomUUID()): Promise<LightMyRequestResponse> {
    return this.request('POST', url, { body, headers: { 'idempotency-key': key } });
  }

  async signUp(name: string, email: string, password: string): Promise<string> {
    const response = await this.request('POST', '/api/auth/sign-up/email', {
      body: { name, email, password },
    });
    if (response.statusCode !== 200) {
      throw new Error(`sign-up failed: ${String(response.statusCode)} ${response.body}`);
    }
    return response.json<{ user: { id: string } }>().user.id;
  }

  async enableTwoFactor(password: string): Promise<void> {
    const enable = await this.request('POST', '/api/auth/two-factor/enable', { body: { password } });
    if (enable.statusCode !== 200) {
      throw new Error(`two-factor enable failed: ${enable.body}`);
    }
    const uri = new URL(enable.json<{ totpURI: string }>().totpURI);
    const code = totp(uri.searchParams.get('secret') ?? '');
    const verify = await this.request('POST', '/api/auth/two-factor/verify-totp', { body: { code } });
    if (verify.statusCode !== 200) {
      throw new Error(`two-factor verify failed: ${verify.body}`);
    }
  }
}

function base32Decode(text: string): Buffer {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
  let bits = '';
  for (const char of text.replace(/=+$/u, '').toUpperCase()) {
    bits += alphabet.indexOf(char).toString(2).padStart(5, '0');
  }
  const bytes: number[] = [];
  for (let index = 0; index + 8 <= bits.length; index += 8) {
    bytes.push(Number.parseInt(bits.slice(index, index + 8), 2));
  }
  return Buffer.from(bytes);
}

/** RFC 6238 TOTP (SHA-1, 6 digits, 30-second period), as generated by authenticator apps. */
export function totp(secret: string, now: number = Date.now()): string {
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(now / 30_000)));
  const digest = createHmac('sha1', base32Decode(secret)).update(counter).digest();
  const offset = (digest.at(-1) ?? 0) & 0x0f;
  const value = (digest.readUInt32BE(offset) & 0x7fffffff) % 1_000_000;
  return String(value).padStart(6, '0');
}
