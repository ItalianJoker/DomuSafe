import {
  authAccounts,
  authSessions,
  authTwoFactors,
  authUsers,
  authVerifications,
  type Database,
} from '@domusafe/db';
import { hash, verify } from '@node-rs/argon2';
import { betterAuth } from 'better-auth';
import { drizzleAdapter } from 'better-auth/adapters/drizzle';
import { twoFactor } from 'better-auth/plugins/two-factor';
import type { KeyValueStore } from '../infra/kv.js';

/** Argon2id parameters for login passwords: RFC 9106 second recommendation (phase 1 §3.6). */
export const PASSWORD_HASH_OPTIONS = { memoryCost: 65_536, timeCost: 3, parallelism: 4 } as const;

const DAY_SECONDS = 86_400;

function secondaryStorageFor(store: KeyValueStore) {
  return {
    get: (key: string) => store.get(key),
    getAndDelete: (key: string) => store.getAndDelete(key),
    increment: (key: string, ttl: number) => store.increment(key, ttl),
    set: (key: string, value: string, ttl?: number) => store.set(key, value, ttl ?? DAY_SECONDS),
    delete: (key: string) => store.delete(key),
  };
}

/** Inputs of `createAuth`. */
export interface AuthOptions {
  readonly db: Database;
  readonly secret: string;
  readonly baseURL: string;
  readonly trustedOrigins: readonly string[];
  readonly production: boolean;
  /** Shared session cache and rate-limit storage (Valkey); database only when `null`. */
  readonly secondaryStorage: KeyValueStore | null;
  /** Called after Better Auth creates an account (creates the domain profile). */
  readonly onUserCreated: (user: { id: string; name: string }) => Promise<void>;
}

/**
 * Builds the Better Auth instance: email and password with Argon2id, TOTP two-factor, database sessions
 * in `auth_*` tables with ids generated by PostgreSQL (`uuidv7()`), no IP tracking on sessions, cookies
 * prefixed `domusafe` (`__Secure-` over HTTPS).
 *
 * @param options - Database, secret derived from the class S master key, origins and storage.
 * @returns The Better Auth instance mounted on `/api/auth`.
 */
export function createAuth(options: AuthOptions) {
  return betterAuth({
    appName: 'DomuSafe',
    baseURL: options.baseURL,
    basePath: '/api/auth',
    secret: options.secret,
    trustedOrigins: [...options.trustedOrigins],
    database: drizzleAdapter(options.db, {
      provider: 'pg',
      schema: {
        user: authUsers,
        session: authSessions,
        account: authAccounts,
        verification: authVerifications,
        twoFactor: authTwoFactors,
      },
    }),
    ...(options.secondaryStorage === null
      ? {}
      : { secondaryStorage: secondaryStorageFor(options.secondaryStorage) }),
    emailAndPassword: {
      enabled: true,
      minPasswordLength: 12,
      maxPasswordLength: 128,
      password: {
        hash: (password: string) => hash(password, PASSWORD_HASH_OPTIONS),
        verify: ({ hash: stored, password }: { hash: string; password: string }) => verify(stored, password),
      },
    },
    session: {
      expiresIn: 30 * DAY_SECONDS,
      updateAge: DAY_SECONDS,
    },
    rateLimit: {
      enabled: options.production,
      window: 60,
      max: 100,
      customRules: {
        '/sign-up/email': { window: 3600, max: 5 },
        '/sign-in/email': { window: 900, max: 10 },
        '/two-factor/*': { window: 300, max: 5 },
        '/forget-password': { window: 3600, max: 3 },
      },
      ...(options.secondaryStorage === null ? {} : { storage: 'secondary-storage' as const }),
    },
    advanced: {
      cookiePrefix: 'domusafe',
      useSecureCookies: options.production,
      ipAddress: { disableIpTracking: true },
      database: { generateId: false },
    },
    databaseHooks: {
      user: {
        create: {
          after: async (user) => {
            await options.onUserCreated({ id: user.id, name: user.name });
          },
        },
      },
    },
    plugins: [twoFactor({ issuer: 'DomuSafe' })],
  });
}

/** Better Auth instance type. */
export type Auth = ReturnType<typeof createAuth>;
