import { z } from 'zod';
import { CURRENCY_CODES } from './currencies.js';

/** Canonical lowercase UUID (any version). */
export const uuidSchema = z.uuid().meta({ description: 'UUID in canonical lowercase form' });
/** UUIDv7 generated in the browser for rows bound into associated data. */
export const uuidV7Schema = z.uuidv7().meta({ description: 'UUIDv7 generated by the client' });
/** RFC 3339 instant in UTC (`Z` suffix). */
export const instantSchema = z.iso.datetime().meta({ description: 'RFC 3339 instant in UTC' });
/** Calendar date `YYYY-MM-DD` in the family time zone. */
export const localDateSchema = z.iso.date().meta({ description: 'Calendar date in the family time zone' });
/** Base64url without padding. */
export const base64UrlSchema = z
  .string()
  .regex(/^[A-Za-z0-9_-]*$/, 'Expected base64url without padding')
  .refine((value) => value.length % 4 !== 1, 'Invalid base64url length')
  .meta({ description: 'Bytes encoded as base64url without padding' });
/** ISO 4217 currency supported by the European Central Bank reference rates. */
export const currencySchema = z.enum(CURRENCY_CODES).meta({ description: 'ISO 4217 currency code' });
/** Interface language. */
export const localeSchema = z.enum(['it', 'en']).meta({ description: 'Interface language' });
/** IANA time zone recognised by the runtime. */
export const timeZoneSchema = z
  .string()
  .min(1)
  .max(64)
  .refine((value) => {
    try {
      new Intl.DateTimeFormat('en', { timeZone: value });
      return true;
    } catch {
      return false;
    }
  }, 'Unknown time zone')
  .meta({ description: 'IANA time zone, for example Europe/Rome' });

/** Amount in minor units with its currency (phase 3 §2.1). */
export const moneySchema = z
  .object({ amountMinor: z.int(), currency: currencySchema })
  .strict()
  .meta({ id: 'Money', description: 'Amount in minor units' });
/** Amount in minor units with its currency. */
export type Money = z.infer<typeof moneySchema>;

/** Encrypted A/B content as transported in JSON (phase 3 §2.1). */
export const sealedSchema = z
  .object({
    scopeId: uuidV7Schema,
    keyVersion: z.int().min(1),
    dek: base64UrlSchema,
    payload: base64UrlSchema,
  })
  .strict()
  .meta({ id: 'Sealed', description: 'Envelope encrypted in the browser (DS-ENV v1)' });
/** Encrypted A/B content as transported in JSON. */
export type Sealed = z.infer<typeof sealedSchema>;

/** Maximum page size of list endpoints. */
export const MAX_PAGE_SIZE = 200;
/** Default page size of list endpoints. */
export const DEFAULT_PAGE_SIZE = 50;

/** Query parameters of cursor-paginated list endpoints. */
export const pageQuerySchema = z
  .object({
    limit: z.coerce.number().int().min(1).max(MAX_PAGE_SIZE).default(DEFAULT_PAGE_SIZE),
    cursor: z.string().max(512).optional(),
  })
  .strict();
/** Parsed pagination query. */
export type PageQuery = z.infer<typeof pageQuerySchema>;

/**
 * Builds the response schema of a cursor-paginated list.
 *
 * @param item - Schema of one item.
 * @returns `{ items, nextCursor }` schema.
 */
export function pageSchema<T extends z.ZodType>(item: T) {
  return z.object({ items: z.array(item), nextCursor: z.string().nullable() }).strict();
}

/** Position of the last row of a page: sort key values and id. */
export type CursorPosition = readonly [sortKey: string | number, id: string];

/**
 * Encodes a keyset cursor as opaque base64url JSON.
 *
 * @param position - Sort key and id of the last returned row.
 * @returns Opaque cursor string.
 */
export function encodeCursor(position: CursorPosition): string {
  const bytes = new TextEncoder().encode(JSON.stringify(position));
  let binary = '';
  for (const byte of bytes) {
    binary += String.fromCharCode(byte);
  }
  return btoa(binary).replaceAll('+', '-').replaceAll('/', '_').replace(/=+$/u, '');
}

/**
 * Decodes a cursor produced by `encodeCursor`.
 *
 * @param cursor - Opaque cursor from a previous page.
 * @returns The position, or `null` when the cursor is malformed (callers answer `400 cursor_invalid`).
 */
export function decodeCursor(cursor: string): CursorPosition | null {
  try {
    const padded = cursor.replaceAll('-', '+').replaceAll('_', '/');
    const binary = atob(padded + '='.repeat((4 - (padded.length % 4)) % 4));
    const bytes = Uint8Array.from(binary, (char) => char.charCodeAt(0));
    const value: unknown = JSON.parse(new TextDecoder().decode(bytes));
    if (
      Array.isArray(value) &&
      value.length === 2 &&
      (typeof value[0] === 'string' || typeof value[0] === 'number') &&
      typeof value[1] === 'string' &&
      uuidSchema.safeParse(value[1]).success
    ) {
      return [value[0], value[1]];
    }
    return null;
  } catch {
    return null;
  }
}

/** Header names of the API conventions (phase 3 §2.2). */
export const HEADERS = {
  ifMatch: 'if-match',
  etag: 'etag',
  idempotencyKey: 'idempotency-key',
  csrf: 'x-domusafe-request',
  requestId: 'x-request-id',
  device: 'x-domusafe-device',
} as const;

/**
 * Formats a version as a strong ETag.
 *
 * @param version - Row version.
 * @returns `"<version>"`.
 */
export function formatEtag(version: number): string {
  return `"${String(version)}"`;
}

/**
 * Parses an `If-Match` header carrying one strong ETag produced by `formatEtag`.
 *
 * @param header - Raw header value.
 * @returns The version, or `null` when the header is absent or not a single DomuSafe ETag.
 */
export function parseIfMatch(header: string | undefined): number | null {
  if (header === undefined) {
    return null;
  }
  const match = /^"([1-9]\d{0,9})"$/.exec(header.trim());
  return match?.[1] === undefined ? null : Number(match[1]);
}
